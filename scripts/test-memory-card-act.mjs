// 记忆卡手动操作：toast 文案不能阻断 reload；禁止再引用不存在的 item。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const src = fs.readFileSync(path.resolve('plugins/surfcore/lib/client.js'), 'utf8');
const cardSrc = fs.readFileSync(path.resolve('plugins/surfcore/lib/memory-card.js'), 'utf8');
const start = src.indexOf('      const act = async (action, extra = {}) => {');
assert.ok(start > 0, '找不到 MemoryCardPanel act');
const block = src.slice(start, start + 2100);
assert.ok(!block.includes('item.staged'), 'act 里不能再引用 item.staged');
assert.ok(block.includes('"✓ 已更新"'), 'fallback 必须是固定文案');
assert.ok(block.includes('reloadFailure'), 'reload 失败必须被记录');
assert.ok(block.includes('界面刷新失败'), 'reload 失败必须给用户提示，不能假装成功');
assert.ok(!block.includes('try { await reload(); } catch {}'), '不能再静默吞掉 reload 错误');
assert.ok(block.indexOf('await reload()') < block.indexOf('toast(action ==='), 'reload 必须先于 toast');
assert.ok(src.includes('function MemoryCardPanel'), 'MemoryCardPanel 必须存在');
assert.ok(!src.includes('disabled: !!busy || record.pinned }, "忘记"'), '初次相遇/置顶记忆不能禁用忘记');
assert.ok(cardSrc.includes('filter((item) => item.id !== id)'), 'forget 必须允许删除 firstMet/pinned');
assert.ok(cardSrc.includes('MEMORY_NOT_FOUND'), 'forget/pin 失败必须有 code');
assert.ok(cardSrc.includes('refreshInitialState(card)'), '删除初次相遇后必须重算接管');
console.log('✅ 记忆卡手动操作通过');
