/**
 * 媒体限额：**唯一真相**
 * ============================================================================
 * 为什么单独一个文件：管道（runtime/index.js）要验数量与体积，
 * 平台包要决定压到多大。两边必须是同一组数字，否则会出现
 * "管道放行、包发不出"或反过来的错位。
 *
 * 这里只放数字，不放处理函数——真正的压图/抽帧/转写要外部工具（sharp/ffmpeg），
 * 属于"接入时"的依赖；在没有真实使用者之前不写空壳函数（不留投机 API）。
 */
export const MEDIA_LIMITS = Object.freeze({
  maxItems: 4,                       // 一次事件最多带几份
  maxBytes: 2 * 1024 * 1024,         // 单份体积上限（管道据此削掉超限项）
  maxImageBytes: 2 * 1024 * 1024,
  maxAudioBytes: 8 * 1024 * 1024,
  maxFrames: 8,                      // 视频最多抽几帧
  maxTranscriptChars: 2000,          // 文字稿裁剪上限
});
